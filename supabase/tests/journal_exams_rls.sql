-- Run after migration *_hackathon_journal_exams_oral.sql. Metadata-only contract test: it reads
-- catalog metadata and calls the two pure question-hash functions; it reads no user rows.
-- Checks: RLS on and owner-only policies (role authenticated, auth.uid()) on the five new tables,
-- no anon access, learning_events append-only with own-material inserts, the journal unique key and
-- triggers, own-material inserts for exam_materials / oral_rubrics, the stored question_hash, the
-- new columns of the old tables (each present, none NOT NULL without a default, because the live
-- client f3b94ba never sends them) with their exact defaults and the open-mistake index, the three
-- RPCs (security invoker, empty search_path, executable by authenticated only) and the question
-- normalisation vectors. Every comparison with a value read from the catalog is NULL-safe
-- (IS DISTINCT FROM): a missing column or default must fail, not pass as NULL.
DO $$
DECLARE
  t text;
  f text;
BEGIN
  FOREACH t IN ARRAY ARRAY['learning_events','exams','exam_materials','exam_questions','oral_rubrics'] LOOP
    IF NOT (SELECT relrowsecurity FROM pg_catalog.pg_class WHERE oid = ('public.' || t)::regclass) THEN
      RAISE EXCEPTION 'RLS is off on %', t;
    END IF;
    IF has_table_privilege('anon', 'public.' || t, 'SELECT') OR has_table_privilege('anon', 'public.' || t, 'INSERT') THEN
      RAISE EXCEPTION 'anon can read or write %', t;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_catalog.pg_policies WHERE schemaname = 'public' AND tablename = t
               AND (roles IS DISTINCT FROM ARRAY['authenticated']::name[]
                    OR coalesce(qual, '') || coalesce(with_check, '') NOT ILIKE '%auth.uid%')) THEN
      RAISE EXCEPTION 'a policy on % is not limited to authenticated owners', t;
    END IF;
  END LOOP;

  IF has_table_privilege('authenticated', 'public.learning_events', 'UPDATE')
     OR has_table_privilege('authenticated', 'public.learning_events', 'DELETE')
     OR EXISTS (SELECT 1 FROM pg_catalog.pg_policies WHERE schemaname = 'public' AND tablename = 'learning_events'
                AND cmd NOT IN ('SELECT', 'INSERT'))
     OR NOT EXISTS (SELECT 1 FROM pg_catalog.pg_policies WHERE schemaname = 'public' AND tablename = 'learning_events'
                    AND cmd = 'INSERT' AND with_check ILIKE '%materials%') THEN
    RAISE EXCEPTION 'learning_events must be append-only and own-material only';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_constraint WHERE conname = 'learning_events_client_event_unique' AND contype = 'u')
     OR NOT EXISTS (SELECT 1 FROM pg_catalog.pg_trigger WHERE tgname = 'learning_events_set_server_fields' AND NOT tgisinternal)
     OR NOT EXISTS (SELECT 1 FROM pg_catalog.pg_trigger WHERE tgname = 'flashcard_progress_touch_reviewed' AND NOT tgisinternal) THEN
    RAISE EXCEPTION 'journal constraint or triggers missing';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_policies WHERE schemaname = 'public' AND tablename = 'exam_materials'
                 AND cmd = 'INSERT' AND with_check ILIKE '%exams%' AND with_check ILIKE '%materials%')
     OR NOT EXISTS (SELECT 1 FROM pg_catalog.pg_policies WHERE schemaname = 'public' AND tablename = 'oral_rubrics'
                    AND cmd = 'INSERT' AND with_check ILIKE '%materials%') THEN
    RAISE EXCEPTION 'exam_materials / oral_rubrics inserts must require own materials';
  END IF;
  IF (SELECT attgenerated FROM pg_catalog.pg_attribute
       WHERE attrelid = 'public.exam_questions'::regclass AND attname = 'question_hash' AND NOT attisdropped)
       IS DISTINCT FROM 's'
     OR NOT EXISTS (SELECT 1 FROM pg_catalog.pg_attrdef d
                      JOIN pg_catalog.pg_attribute a ON a.attrelid = d.adrelid AND a.attnum = d.adnum
                     WHERE d.adrelid = 'public.exam_questions'::regclass AND a.attname = 'question_hash'
                       AND pg_catalog.pg_get_expr(d.adbin, d.adrelid) ILIKE '%meldy_question_hash(%') THEN
    RAISE EXCEPTION 'exam_questions.question_hash must be a stored column generated by meldy_question_hash(text)';
  END IF;
  IF EXISTS (SELECT 1
               FROM (VALUES ('exam_sessions', 'kind'), ('exam_sessions', 'duration_seconds'),
                            ('mistake_diary', 'exam_session_id'), ('mistake_diary', 'source_ids'),
                            ('mistake_diary', 'origin'), ('mistake_diary', 'item_key'),
                            ('mistake_diary', 'rubric_point_id'), ('flashcard_progress', 'last_reviewed_at'),
                            ('flashcard_progress', 'origin'), ('flashcard_progress', 'source_ids')) AS wanted (tbl, col)
               LEFT JOIN information_schema.columns c
                 ON c.table_schema = 'public' AND c.table_name = wanted.tbl AND c.column_name = wanted.col
              WHERE c.column_name IS NULL OR (c.is_nullable = 'NO' AND c.column_default IS NULL)) THEN
    RAISE EXCEPTION 'a new column of an old table is missing or NOT NULL without a default (the live client never sends it)';
  END IF;
  IF (SELECT column_default FROM information_schema.columns WHERE table_schema = 'public'
       AND table_name = 'exam_sessions' AND column_name = 'kind') IS DISTINCT FROM '''professor''::text'
     OR (SELECT column_default FROM information_schema.columns WHERE table_schema = 'public'
          AND table_name = 'mistake_diary' AND column_name = 'origin') IS DISTINCT FROM '''professor''::text'
     OR (SELECT column_default FROM information_schema.columns WHERE table_schema = 'public'
          AND table_name = 'flashcard_progress' AND column_name = 'origin') IS DISTINCT FROM '''analysis''::text' THEN
    RAISE EXCEPTION 'old-client rows must default to kind/origin professor and card origin analysis';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_indexes WHERE schemaname = 'public' AND indexname = 'mistake_diary_open_item_key_uidx'
                 AND indexdef ILIKE '%item_key IS NOT NULL%') THEN
    RAISE EXCEPTION 'the open-mistake index mistake_diary_open_item_key_uidx is missing';
  END IF;

  FOREACH f IN ARRAY ARRAY['public.review_flashcard(uuid,integer,text,date,uuid)',
                           'public.record_quiz_attempt(jsonb)',
                           'public.record_oral_attempt(jsonb)'] LOOP
    IF to_regprocedure(f) IS NULL
       OR (SELECT prosecdef FROM pg_catalog.pg_proc WHERE oid = to_regprocedure(f))
       OR NOT coalesce((SELECT proconfig FROM pg_catalog.pg_proc WHERE oid = to_regprocedure(f)) @> ARRAY['search_path=""'], false)
       OR NOT has_function_privilege('authenticated', f, 'EXECUTE')
       OR has_function_privilege('anon', f, 'EXECUTE') THEN
      RAISE EXCEPTION 'rpc % must exist, be security invoker with an empty search_path, executable by authenticated only', f;
    END IF;
  END LOOP;

  IF public.meldy_normalize_question('17. Денежно-кредитная политика ЦБ: цели, инструменты!') IS DISTINCT FROM 'денежно кредитная политика цб цели инструменты'
     OR public.meldy_normalize_question('Вопрос 3) Ёлка и ЕЛЬ') IS DISTINCT FROM 'елка и ель'
     OR public.meldy_normalize_question('  1.2. Предмет и метод макроэкономики.') IS DISTINCT FROM 'предмет и метод макроэкономики'
     OR public.meldy_normalize_question('1917 год: революция') IS DISTINCT FROM '1917 год революция'
     OR public.meldy_normalize_question('5.Инфляция: виды') IS DISTINCT FROM 'инфляция виды'
     OR public.meldy_normalize_question('Вопрос №12. Рынок труда') IS DISTINCT FROM 'рынок труда'
     OR public.meldy_question_hash('Предмет и метод макроэкономики') IS DISTINCT FROM 'eee8c9ac62e0050c8e2065db1ebed8cc' THEN
    RAISE EXCEPTION 'question normalisation vectors failed';
  END IF;
END
$$;
