import { describe, expect, it } from 'vitest';
import raw from '../../../../contracts/learn_left/vectors.json?raw';
import { buildSheet } from './cheatSheet';
import { parseSheetResponse } from './sheetResponse';
import { questionFacts, type QuestionFacts } from './learnFacts';
import { learnLeftCases, type LearnLeftCase } from './__fixtures__/learnLeftCases';

/**
 * contracts/learn_left/vectors.json: the shared cases of «learned» for oral questions. The site's line rule computes the
 * expected facts here; supabase/tests/local/learn_left_run.sh checks meldy_private.learn_left_facts against the same file.
 * Regenerate after a change of the rule or the cases (in UTC: the vectors' moments are UTC):
 *   TZ=UTC WRITE_LEARN_LEFT_VECTORS=1 npx vitest run src/lib/exams/learnFacts.vectors.test.ts
 */
// The project has no Node types; the test runs in Node only (as quietLinks.test.ts reads files).
interface NodeFs {
  writeFileSync(path: string, text: string): void;
}
const NODE_FS: string = 'node:fs';
const env = (globalThis as unknown as { process?: { env: Record<string, string | undefined>; cwd(): string } }).process;

interface VectorFile {
  v: 1;
  about: string;
  cases: Array<LearnLeftCase & { expect: Array<Omit<QuestionFacts, 'learnedAt' | 'readyAt'> & { learned_at: number | null; ready_at: number | null }> }>;
}

function factsOf(c: LearnLeftCase): QuestionFacts[] {
  const parsed = parseSheetResponse(c.sheet);
  const built = buildSheet(parsed.questions, c.events, Date.parse(c.now));
  const blocks = new Map(built.blocks.map((block) => [block.questionId, block]));
  return parsed.questions.map((question) => questionFacts(question, blocks.get(question.question_id)));
}

const wire = (f: QuestionFacts) => ({ id: f.id, kind: f.kind, state: f.state, named: f.named, of: f.of, learned_at: f.learnedAt, ready_at: f.readyAt, missed: f.missed });
// The line rule reads local days in the browser's zone; the vectors are UTC.
const utc = new Date('2026-10-01T00:00:00Z').getTimezoneOffset() === 0 && new Date('2026-07-01T00:00:00Z').getTimezoneOffset() === 0;

describe('learn_left vectors (contracts/learn_left/vectors.json)', () => {
  if (env?.env.WRITE_LEARN_LEFT_VECTORS === '1') {
    it('are written', async () => {
      expect(utc).toBe(true);
      const file: VectorFile = {
        v: 1,
        about:
          'The facts of public.learn_left per oral question, from the site\'s line rule (frontend/src/lib/exams/learnFacts.ts over cheatSheet.ts buildSheet). Generated by learnFacts.vectors.test.ts (TZ=UTC WRITE_LEARN_LEFT_VECTORS=1); checked against meldy_private.learn_left_facts by supabase/tests/local/learn_left_run.sh. Moments in epoch seconds; do not edit by hand.',
        cases: learnLeftCases().map((c) => ({ ...c, expect: factsOf(c).map(wire) })),
      };
      const fs = (await import(/* @vite-ignore */ NODE_FS)) as NodeFs;
      fs.writeFileSync(`${env!.cwd()}/../contracts/learn_left/vectors.json`, `${JSON.stringify(file, null, 1)}\n`);
    });
    return;
  }

  const file = JSON.parse(raw) as VectorFile;

  it('hold exactly the cases of learnLeftCases.ts', () => {
    const cases = learnLeftCases();
    expect(file.cases.map((c) => c.name)).toEqual(cases.map((c) => c.name));
    for (const [i, c] of cases.entries()) {
      expect(file.cases[i].sheet).toEqual(JSON.parse(JSON.stringify(c.sheet)));
      expect(file.cases[i].events).toEqual(JSON.parse(JSON.stringify(c.events)));
      expect(file.cases[i].now).toBe(c.now);
    }
  });

  for (const c of file.cases) {
    it(`${c.name}: the site's rule gives the stored facts`, () => {
      const got = factsOf(c).map(wire);
      // Outside UTC the ready moment's midnight moves with the zone: the rest must still agree.
      const strip = (rows: typeof got) => (utc ? rows : rows.map((row) => ({ ...row, ready_at: null })));
      expect(strip(got)).toEqual(strip(c.expect));
    });
  }

  it('cover learned, waiting, partly named, missed and every kind', () => {
    const all = file.cases.flatMap((c) => c.expect);
    for (const state of [0, 1, 2, 3]) expect(all.some((f) => f.state === state)).toBe(true);
    expect(all.some((f) => f.missed)).toBe(true);
    expect(all.some((f) => f.ready_at !== null)).toBe(true);
    for (const kind of ['lines', 'unwritten', 'rebuilt', 'none', 'gap', 'unmapped', 'unverified']) expect(all.some((f) => f.kind === kind)).toBe(true);
  });
});
