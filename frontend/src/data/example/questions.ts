/**
 * «Вопросы к экзамену по микроэкономике»: the example's department list, already checked against its
 * three lectures — nine questions are in them, two partly, one not at all (the honest «нет в лекциях»).
 *
 * Every mark carries its evidence: the lecture, the fragment and a quote cut word for word from the
 * lecture text. Every question that can be answered carries its answer points in the shape of a
 * rubric from /api/oral/rubric (oralApi.RubricPoint, contracts §5): a title, essential or not, a
 * verbatim lecture quote, the key-word anchors the live marks match (rubricMatch.ts: group 0 is the
 * notion, its first variant starts a word of the point's fragment; 2–4 groups of 1–4 word beginnings;
 * no variant shared by two points) and the examiner's follow-up. example.test.ts holds all of it to
 * the server's rules (backend/oral.py validate_rubric) and to the client's own parseRubricResponse.
 */
import type { LectureKey } from './lectures';

export interface ExampleEvidence {
  lecture: LectureKey;
  /** «S02» */
  fragment: string;
  /** Word for word from the lecture. */
  quote: string;
}

export interface ExampleNearest {
  lecture: LectureKey;
  fragment: string;
  /** Words of the question that the fragment also has — and nothing more. */
  matched: string[];
}

export interface ExamplePoint {
  title: string;
  /**
   * The point's line on the cheat sheet, written by hand by the rules the server's short lines keep
   * (sheet spec 3.3): only the title's own words, ↑ ↓ → = > < as the title says, no new fact.
   */
  short: string;
  essential: boolean;
  /** Word for word from the lecture: a continuous piece of the fragments below. */
  quote: string;
  /** The fragments of the quote, in the question's lecture. */
  fragments: string[];
  anchors: string[][];
  followup: { question: string; expected: string };
}

export interface ExampleQuestion {
  /** «q1» … «q12» */
  id: string;
  /** The department's number. */
  number: number;
  text: string;
  coverage: 'full' | 'partial' | 'none';
  /** Why the mark (the «почему» of the sheet). */
  reason: string;
  /** What the lectures lack (partial): «Не хватает: …». */
  missing: string;
  evidence: ExampleEvidence[];
  /** A question that is in no lecture: the closest fragment and the words it shares. */
  nearest: ExampleNearest | null;
  /** The lecture the answer points come from (null when there is nothing to answer against). */
  lecture: LectureKey | null;
  /** Partial questions: what the answer points leave out because the lectures do. */
  coverageNote: string;
  points: ExamplePoint[];
}

