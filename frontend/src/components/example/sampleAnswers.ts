/** The ready answer to a question of the example, or null (a question in no lecture has nothing to check against). */
export function sampleAnswer(question: Pick<ExampleQuestion, 'id'> | null | undefined): string | null {
  return (question && SAMPLE_ANSWERS[question.id]) || null;
}

/** Whether the answer field holds the ready answer as it was put in (its label then says so, not «Ваш ответ»). */
export function isSampleAnswer(question: Pick<ExampleQuestion, 'id'>, text: string): boolean {
  const sample = sampleAnswer(question);
  return sample !== null && text.trim() !== '' && text.trim() === sample.trim();
}
