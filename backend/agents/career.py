from .base import BaseAgent
import json
import asyncio

def build_career_prompt() -> str:
    return """Ты — ведущий карьерный консультант, HR-эксперт крупного ИТ-холдинга и технический ментор.
Проанализируй предоставленный список изученных студентом тем, терминов и концепций из материалов, оцени глубину его знаний и сформируй премиальный, профессиональный карьерный профиль.

ОБЯЗАТЕЛЬНО верни ответ строго в формате JSON без markdown-обёртки (НИКАКИХ ```json или ```):
{
  "skills": ["Навык 1", "Навык 2"],
  "professions": [
    {"title": "Название профессии", "match": 85}
  ],
  "resume_summary": "Текст 'О себе' для резюме (2-3 емких абзаца, подчеркивающие хард-скиллы).",
  "projects": [
    {"title": "Название проекта", "description": "Детальное и привлекательное техническое описание пет-проекта"}
  ]
}

ИНСТРУКЦИЯ ПО ЗАПОЛНЕНИЮ:
1. "skills": Выдели 5-10 конкретных, востребованных на рынке труда хард-скиллов (конкретные технологии, фреймворки, архитектурные паттерны или методологии), которые напрямую следуют из изученного материала.
2. "professions": Предложи 2-4 реальные, современные ИТ-профессии (например: Backend-разработчик (Python/Django), Системный аналитик, Frontend-разработчик (React)). Укажи точный процент соответствия (match) от 50 до 100% на основе покрытия тем.
3. "resume_summary" (КРИТИЧЕСКИ ВАЖНО): Напиши потрясающее, цепляющее саммари "О себе" для CV на русском языке. Оно должно звучать зрело и профессионально (без шаблонных фраз вроде "быстро учусь"), подчеркивать реальный стек, концептуальное понимание проектирования и практическую готовность к стажировкам или Junior-позициям.
4. "projects": Предложи 2-3 идеи для крутых пет-проектов в портфолио, которые идеально ложатся на стек изученных материалов. Каждое описание должно быть сформулировано коммерчески привлекательно: "Разработка высоконагруженного сервиса для... с использованием..."
"""

class CareerAgent(BaseAgent):
    """
    Агент для генерации карьерного профиля на основе материалов.
    """
    
    async def process(self, context: str) -> dict:
        """
        context: Сборная строка всех тем и конспектов пользователя.
        """
        prompt = build_career_prompt()
        raw_result = await self.run(prompt, context)
        
        # Парсинг JSON
        try:
            # Очистка от возможных markdown-оберток
            cleaned = raw_result.strip()
            if cleaned.startswith("```json"):
                cleaned = cleaned[7:]
            if cleaned.startswith("```"):
                cleaned = cleaned[3:]
            if cleaned.endswith("```"):
                cleaned = cleaned[:-3]
            
            return json.loads(cleaned.strip())
        except Exception as e:
            # Fallback in case of failure
            return {
                "skills": ["Анализ данных", "Обучаемость"],
                "professions": [{"title": "Студент-исследователь", "match": 100}],
                "resume_summary": "Активно изучаю новые материалы и стремлюсь к профессиональному развитию.",
                "projects": [{"title": "Продолжить обучение", "description": "Изучить больше материалов для точного анализа."}],
                "error": f"JSON Parse Error: {str(e)}"
            }
